def write_deep() -> None:
    raw = RAW.read_text(encoding="utf-8-sig")
    header = """---
source_id: SRC-OBJECTIONS-01
topic: objections_and_partner_training
source_type: internal_training_material
source_title: Возражения. Отработка
source_path: D:/Obsidian/WHIEDA/05_WHIEDA_RAG/Возражения. Отработка.md
review_status: business_review_required
publication_scope: internal_rag_only
created_at: 2026-07-15
---

# Возражения и отработка: полный внутренний учебный материал

## Рамка безопасного использования

Этот файл сохраняет полный учебный материал. Он описывает техники общения, личный опыт и продающие подходы лидеров, а не гарантии дохода, свойств продукта или результата.

Для публичного ответа:

- сначала выслушать, уточнить суть и ответить по подтверждённым данным;
- цену, PV, W$, товар, фото, видео и правила брать из structured SQL;
- не спорить, не стыдить, не давить и не обещать доход/окупаемость/лечение;
- личные истории и результаты считать опытом автора, а не доказательством;
- при юридическом, финансовом или медицинском вопросе не импровизировать.

---

"""
    DEEP.write_text(header + raw, encoding="utf-8")


def write_sql_cards() -> None:
    fields = [
        "objection_id", "title", "aliases", "first_reply", "clarify",
        "confirmed_answer_rule", "next_step", "do_not_say", "status", "source_id",
    ]
    with SQL.open("w", encoding="utf-8-sig", newline="") as out:
        writer = csv.DictWriter(out, fieldnames=fields)
        writer.writeheader()
        for card in CARDS:
            writer.writerow({**card, "status": "PROPOSED_BUSINESS_REVIEW", "source_id": "SRC-OBJECTIONS-01"})


